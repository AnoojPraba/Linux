/*****************************************************************************
 * Name: addTwo
 *
 * Description:
 *         Adds two to the given value.
 *
 * Inputs:
 *         value : the value to increment by two.
 *
 * Returns:
 *         value + 2.
 *****************************************************************************/
int addTwo(int value)
{
    return value + 2;
}
